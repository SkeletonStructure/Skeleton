import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ARTIFACT = fileURLToPath(new URL('../openapi/openapi.json', import.meta.url));
const TARGET = fileURLToPath(new URL('../packages/sdk/generated/api.ts', import.meta.url));
const HTTP_METHODS = new Set(['get', 'post', 'put', 'patch', 'delete']);

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

export function operationBaseName(path, method) {
  const words = path
    .split('/')
    .filter((segment) => segment.length > 0 && segment !== 'v1')
    .flatMap((segment) => segment.split(/[-_]/))
    .filter((word) => word.length > 0)
    .map(capitalize);
  return `${words.join('')}${capitalize(method)}`;
}

function quote(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function isIdentifier(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value);
}

function renderType(schema, level) {
  if (schema === undefined || schema === null) return 'unknown';

  if (Array.isArray(schema.enum)) {
    return schema.enum.length > 0 ? schema.enum.map(quote).join(' | ') : 'never';
  }

  const indent = '  '.repeat(level);
  const closingIndent = '  '.repeat(Math.max(0, level - 1));

  switch (schema.type) {
    case 'object': {
      const properties = schema.properties ?? {};
      const entries = Object.entries(properties);
      if (entries.length === 0) return 'Record<string, never>';
      const required = new Set(schema.required ?? []);
      const lines = entries.map(([key, value]) => {
        const name = isIdentifier(key) ? key : quote(key);
        const optional = required.has(key) ? '' : '?';
        return `${indent}${name}${optional}: ${renderType(value, level + 1)};`;
      });
      return `{\n${lines.join('\n')}\n${closingIndent}}`;
    }
    case 'array':
      return `Array<${renderType(schema.items, level)}>`;
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    default:
      return 'unknown';
  }
}

function operationSchemas(document) {
  const result = [];
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem ?? {})) {
      if (!HTTP_METHODS.has(method) || typeof operation !== 'object' || operation === null)
        continue;
      const base = operationBaseName(path, method);
      const response = operation.responses?.['200']?.content?.['application/json']?.schema;
      const body = operation.requestBody?.content?.['application/json']?.schema;
      result.push({ base, response, body });
    }
  }
  return result;
}

export function generateSdkTypes(document) {
  const lines = [
    '// Generated by scripts/generate-sdk.mjs from openapi/openapi.json.',
    '// Do not edit this file directly.',
    '',
  ];

  for (const { base, response, body } of operationSchemas(document)) {
    if (response !== undefined) {
      lines.push(`export type ${base}Response = ${renderType(response, 1)};`, '');
    }
    if (body !== undefined) {
      lines.push(`export type ${base}Body = ${renderType(body, 1)};`, '');
    }
  }

  return lines.join('\n');
}

export async function buildGeneratedSdkTypes() {
  const document = JSON.parse(await readFile(ARTIFACT, 'utf8'));
  return generateSdkTypes(document);
}

export async function writeGeneratedSdkTypes() {
  const output = await buildGeneratedSdkTypes();
  await writeFile(TARGET, output, 'utf8');
  return TARGET;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = await writeGeneratedSdkTypes();
  console.log(`Wrote ${target}`);
}
