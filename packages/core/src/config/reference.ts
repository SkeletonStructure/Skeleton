function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}

export function renderConfigReference(): string {
  const rows = CONFIG_FIELDS.map((field) => {
    const env = field.env === null ? '—' : `\`${field.env}\``;
    const required = field.required ? 'yes' : 'no';
    const secret = field.secret ? 'yes' : 'no';
    const defaultValue = field.defaultValue === null ? '—' : `\`${field.defaultValue}\``;
    return `| \`${field.path}\` | ${env} | ${required} | ${secret} | \`${escapeCell(field.type)}\` | ${defaultValue} | ${escapeCell(field.description)} |`;
  });

  return [
    '# Configuration reference',
    '',
    'This file is generated from the core configuration field metadata. Do not edit it by hand.',
    '',
    'Regenerate with `pnpm config:docs`.',
    '',
    '## Precedence',
    '',
    '1. Process environment variables',
    '2. `.env.local`',
    '3. `.env`',
    '4. `skeleton.config.ts` values',
    '5. Built-in defaults',
    '',
    'Secret fields can only be supplied through environment variables using `env(...)` in the config file. Literal secrets in `skeleton.config.ts` fail validation.',
    '',
    '## Fields',
    '',
    '| Field | Environment variable | Required | Secret | Type | Default | Description |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}
